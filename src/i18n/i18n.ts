export const DICTIONARIES: Record<Language, Dict> = {
    [Language.English]: en,
    [Language.Chinese]: zh,
    [Language.Japanese]: ja,
    [Language.Malay]: ms,
    [Language.Tamil]: ta,
};

export type TranslationKey = keyof typeof en;

function applyVars(template: string, vars?: TranslationVars): string {
    if (!vars) return template;

    return template.replace(/\{(\w+)\}/g, (match, name) =>
        name in vars ? String(vars[name]) : match,
    );
}

export function translate(language: Language, key: TranslationKey, vars?: TranslationVars): string {
    const template = DICTIONARIES[language]?.[key] ?? en[key] ?? key;
    return applyVars(template, vars);
}

/** Tab names double as identity, so display falls back to the raw name. */
export function translateTabName(language: Language, name: string): string {
    return DICTIONARIES[language]?.[`tab.${name}`] ?? en[`tab.${name}`] ?? name;
}

export function translateSettingsPageName(language: Language, name: string): string {
    return DICTIONARIES[language]?.[`settings.page.${name}`] ?? name;
}

/** Stock label for material cards: exact count when known, status otherwise. */
export function translatedStockLabel(language: Language, material: Material): string {
    if (material.quantity > 0) {
        return `${material.quantity} ${material.unit}`;
    }

    const key: TranslationKey = material.stockStatus === "in-stock" ? "stock.inStock"
        : material.stockStatus === "low" ? "stock.low"
        : material.stockStatus === "wishlist" ? "stock.wishlist"
        : material.stockStatus === "missing" ? "stock.missing"
        : "stock.out";

    return translate(language, key);
}

export function getCurrentLanguage(): Language {
    return loadAppearancePrefs().language;
}

export function useI18n() {
    const [language, setLanguage] = useState<Language>(getCurrentLanguage);

    useEffect(() => {
        const onChange = () => setLanguage(getCurrentLanguage());

        window.addEventListener("viventory:appearance-change", onChange);
        return () => window.removeEventListener("viventory:appearance-change", onChange);
    }, []);

    const t = (key: TranslationKey, vars?: TranslationVars) => translate(language, key, vars);

    return { language, t };
}
